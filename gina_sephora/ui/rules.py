NEW_STOCK_RULES = """
- **销量来源**：勾选使用 benchmark 时，按 SKU 表中对应 benchmark 的历史销量计算；不勾选时，按 Material 自身的历史销量计算。库存扣减及出库结果始终归属 Material，共用 benchmark 的不同 Material 各自分配自己的库存，不共用库存。
- **SOB** = 销量来源货号在该店的销量 ÷ 该货号在当前有效门店中的销量合计。不在当前 Store list 中的门店不参与计算，剩余门店的占比重新归一到 100%。
- **常规目标量** = SOB × 扣除 DM 需求后的可分配库存（DM 关闭时为全部可分配库存）。先向下取整，剩余库存按小数余数从大到小补齐；余数相同时按店号文本升序补齐。
- 当前门店在整个销售文件中没有记录时，标记为**新店／无历史销售记录**，SOB 为 0、allocation 为 **-10**，该标记不计入常规目标合计；若适用 DM，仍实际出库并扣库存。
- 旧店有历史记录，但销量来源货号在该店没有销量或销量为 0 时，SOB 和基础 allocation 均为 **0**。
- 销量来源货号的有效销量合计为 0 时，常规库存暂不分配，但仍可从库存分配 DM；同 SKU 同店多条记录按销量相加，汇总后存在负销量时暂停整个 SKU（包括 DM）并提示确认。
- 每个 SKU 先尽量满足门店目标量，再优先使用对应 CDC；不足时最多从**一个其他 CDC**调货，并让最终各 CDC 剩余库存尽量均衡。调货后仍无法拿满的门店标记缺货。
- **DM 优先出库**：SKU DM=315 时对当前全部门店各 1 件；DM=251 时仅对门店 DM=1 各 1 件；空白或 0 不产生 DM 需求。先预留全部 DM 需求，剩余库存按 SOB 计算常规目标，新店和零销量店同样适用。
- **库存不足或 CDC 限制导致 DM 无法全部满足**时，整个 SKU 暂停，不发布部分 DM 或常规出库。CDC 计算尚未确认时标记待确认，相关数量留空。
- DM 与常规分货合并为同一次 CDC 出库，每家适用门店的 DM 必须满足；合计仍最多使用优先 CDC 和一个其他 CDC。
- **实际出库量 = 常规实际出库 + DM 实际出库 = 最终分配量**。所有 CDC 出库均包含 DM；“DM 加量”兼容列仅表示已包含的 DM 实际出库，不额外相加。
- **基础 allocation**为常规目标；allocation 为常规目标加 DM 需求，新店保留 -10。DM 需求和 DM 实际出库单列，含 DM 目标合计也包含新店 DM。总库存 = 常规实际出库 + DM 实际出库 + 剩余库存。"""


EXISTING_STOCK_RULES = """
- **门店需求量** = max(0, Mini + Sales qty − Total Stock − Order Quantity)，按 Material 与 Store 匹配，不使用 benchmark 或 SOB。
- **自动比例** = min(100%, 所有 CDC 库存合计 ÷ 当前有效门店需求合计)。总需求为 0 时无需分货。
- **手动比例**按 item 设置，同一 item 的全部门店统一使用。在原生表格最后一列填写 0–100 的数字，有效范围为 0–自动比例上限；超出后回退并提示。留空使用自动比例，填 0 暂不分配；手动精度为 0.01 个百分点。
- 默认使用完整自动比例；用户可填写手动比例降低比例，库存充足时也可只按 80% 等比例分配，未分出的库存留仓。
- **整数目标量**：按每店需求 × 比例先向下取整，再按原小数余数降序补齐至 floor(总需求 × 比例)；并列按店号文本升序。每店目标不超过该店需求，总目标不超过库存。
- **缺失需求记录**：标记“需求数据缺失，暂不分配”，保留需求与目标为空，不补 0、不标 -10；自动比例的需求分母只包含完整记录。
- 同一 Material + Store 只能有一条记录。四个需求字段必须为整数且不能为空；Sales qty 允许负数并直接参与公式，Mini、Total Stock、Order Quantity 不允许负数。
- **CDC 出库**继续优先使用对应 CDC，每店最多再使用一个其他 CDC。比例目标可能因该约束无法全部出库，差额单独标记为缺货。
- **比例缩减量** = 需求量 − 整数目标量；**缺货量** = 整数目标量 − 实际出库量；**未满足需求量** = 需求量 − 实际出库量。
- **DM**保留原功能代码，但现货页控件禁用，不调用 DM 加量。现货最终分配量等于实际出库量。
"""
